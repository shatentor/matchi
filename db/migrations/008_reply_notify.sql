-- Уведомления автору об отзывах на его посты: комментарии и реакции.
--
-- Зачем: автор не узнаёт, что его пост прокомментировали или отметили реакцией,
-- и для сети из десятка друзей это главная причина перестать писать — человек
-- пишет в пустоту. Уведомление о новом посте (feed_notify) на этот вопрос не
-- отвечает: оно про чужие посты, а не про отклик на свои.
--
-- Зачем отдельный флаг, а не переиспользование feed_notify: это разные желания.
-- «Сообщайте о новых постах в сети» — веер по всем участникам, его выключают
-- из-за объёма. «Сообщайте об отзывах на мои посты» — единичные адресные
-- сообщения, их хотят даже те, кто отключил веер. Один флаг заставлял бы
-- выбирать между шумом и глухотой.
--
-- Значение по умолчанию TRUE: у уже зарегистрированных пользователей колонка
-- заполнится сразу, а отключить уведомления человек может сам (/feed_notify).
--
-- Идемпотентность: db/migrate.py прогоняет файл целиком одним execute, поэтому
-- каждый объект создаётся через IF NOT EXISTS — повторный прогон не должен
-- ронять схему.

ALTER TABLE users ADD COLUMN IF NOT EXISTS reply_notify BOOLEAN NOT NULL DEFAULT TRUE;

-- О чьей реакции на какой пост автора УЖЕ уведомляли.
--
-- Зачем отдельная таблица, а не факт наличия строки в post_reactions: реакция
-- переключается тем же нажатием, и снятие физически удаляет строку
-- (PRIMARY KEY (post_id, tg_chat_id), DELETE в PostRepository.set_reaction).
-- Поэтому по самим реакциям цикл «поставил — снял — поставил» выглядит как две
-- первые реакции, и один шутник за минуту нащёлкал бы автору десяток
-- уведомлений. Отметка здесь остаётся навсегда, поэтому автор узнаёт о каждом
-- человеке ровно один раз на пост.
--
-- Счётчиков и «когда именно» тут не нужно: единственный вопрос к таблице —
-- «уведомляли ли уже», ответ даёт наличие строки. notified_at оставлен для
-- разбора жалоб на спам.
CREATE TABLE IF NOT EXISTS post_reaction_notices (
    post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    tg_chat_id VARCHAR(20) NOT NULL REFERENCES users(tg_chat_id) ON DELETE CASCADE,
    notified_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (post_id, tg_chat_id)
);
